/** 글자 한 칸 너비(간격 포함, scale 1 기준) */
const CHAR_W = 4;
const CHAR_H = 5;

/** 문자열 픽셀 너비 */
function textWidth(str, scale = 1) {
  return str.length ? (str.length * CHAR_W - 1) * scale : 0;
}

/**
 * 비트맵 글자 그리기
 * @param {CanvasRenderingContext2D} ctx
 * @param {string} str
 * @param {number} x 왼쪽 위 x
 * @param {number} y 왼쪽 위 y
 * @param {string} col 색
 * @param {number} scale 배율(정수)
 * @param {string|null} shadow 그림자 색(오른쪽 아래 1px), null이면 없음
 */
function drawText(ctx, str, x, y, col = '#fff', scale = 1, shadow = null) {
  str = String(str);
  if (shadow) drawText(ctx, str, x + scale, y + scale, shadow, scale, null);
  ctx.fillStyle = col;
  x = Math.round(x); y = Math.round(y);
  for (let i = 0; i < str.length; i++) {
    let ch = str[i];
    let g = GLYPHS[ch];
    if (!g) g = GLYPHS[ch.toUpperCase()] || GLYPHS['?'];
    for (let r = 0; r < 5; r++) {
      const row = g[r];
      for (let c = 0; c < 3; c++) {
        if (row[c] === '1') ctx.fillRect(x + (i * CHAR_W + c) * scale, y + r * scale, scale, scale);
      }
    }
  }
}

// ───────── 공개 ─────────
G.font = { CHAR_W, CHAR_H, textWidth, drawText };
