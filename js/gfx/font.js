const FONT={'0':'111101101101111','1':'010110010010111','2':'111001111100111','3':'111001111001111','4':'101101111001001','5':'111100111001111',
 '6':'111100111101111','7':'111001001001001','8':'111101111101111','9':'111101111001111','x':'000101010101000','E':'111100110100111','-':'000000111000000'};
function txt(s,x,y,col){
  for(const [c,ox] of [['#120f1c',1],[col,0]]){ctx.fillStyle=c;
    for(let i=0;i<s.length;i++){const g=FONT[s[i]];if(!g)continue;for(let j=0;j<15;j++)if(g[j]==='1')ctx.fillRect(x+i*4+(j%3)+ox,y+Math.floor(j/3)+ox,1,1);}}
}
